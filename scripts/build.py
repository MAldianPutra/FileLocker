"""Build a FileLocker release. Used by build.bat and by the GitHub release workflow,
so local and CI builds are produced the same way.

Steps:
  1. Write _build_info.py (version, commit, build date) and the exe's version resource.
  2. Run PyInstaller (--onedir --windowed), excluding network/web modules.
  3. Add README, LICENSE, SECURITY, VERIFYING, CHANGELOG and THIRD_PARTY_LICENSES.
  4. Run the built exe's own self-test (`FileLocker.exe --selftest`); fail if it fails.
  5. Zip dist/FileLocker into release/ and write SHA256SUMS.txt.

Usage:  python scripts/build.py            (run from the project folder, inside the build venv)
"""

from __future__ import annotations

import datetime as dt
import hashlib
import importlib.metadata as md
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import selftest  # noqa: E402  (only for the NOT_BUNDLED list)
import version  # noqa: E402

DIST = ROOT / "dist" / "FileLocker"
WORK = ROOT / "build"
RELEASE = ROOT / "release"
DOCS = ["README.md", "LICENSE", "SECURITY.md", "VERIFYING.md", "CHANGELOG.md"]
EXCLUDE = sorted(set(selftest.NOT_BUNDLED) | {"_ssl", "openpyxl", "pip", "setuptools", "unittest"})


def log(msg: str) -> None:
    print(f"=== {msg}", flush=True)


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def build_metadata() -> dict:
    commit = os.environ.get("GITHUB_SHA") or git("rev-parse", "HEAD") or "unknown"
    if commit != "unknown" and not os.environ.get("GITHUB_SHA") and git("status", "--porcelain"):
        commit += "-dirty"  # local build with uncommitted changes
    if os.environ.get("GITHUB_ACTIONS") == "true":
        builder = (f"GitHub Actions: {os.environ.get('GITHUB_REPOSITORY', '?')} "
                   f"run {os.environ.get('GITHUB_RUN_ID', '?')}")
    else:
        builder = "local build"
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    when = dt.datetime.fromtimestamp(int(epoch), dt.timezone.utc) if epoch else dt.datetime.now(dt.timezone.utc)
    return {"commit": commit, "date": when.strftime("%Y-%m-%d %H:%M UTC"), "builder": builder}


def write_build_info(meta: dict) -> None:
    (ROOT / "_build_info.py").write_text(
        '"""Generated by scripts/build.py - do not edit, not in git."""\n'
        f"COMMIT = {meta['commit']!r}\nBUILD_DATE = {meta['date']!r}\nBUILDER = {meta['builder']!r}\n",
        encoding="utf-8")


def write_version_resource(meta: dict) -> Path:
    nums = [int(x) for x in re.findall(r"\d+", version.__version__)[:3]] + [0]
    nums = (nums + [0, 0, 0, 0])[:4]
    tup = ", ".join(map(str, nums))
    text = f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers=({tup}), prodvers=({tup}), mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'FileLocker contributors'),
      StringStruct('FileDescription', 'FileLocker - offline password protection for xlsx, docx and pdf'),
      StringStruct('FileVersion', '{version.__version__}'),
      StringStruct('InternalName', 'FileLocker'),
      StringStruct('LegalCopyright', 'MIT License'),
      StringStruct('OriginalFilename', 'FileLocker.exe'),
      StringStruct('ProductName', 'FileLocker'),
      StringStruct('ProductVersion', '{version.__version__} ({meta['commit'][:12]})'),
      StringStruct('Comments', 'Offline tool. No network access. Source: see README.md'),
    ])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    WORK.mkdir(exist_ok=True)
    path = WORK / "version_info.txt"
    path.write_text(text, encoding="utf-8")
    return path


def _lock_names(lock: Path) -> list[str]:
    return [m.group(1) for m in re.finditer(r"^([A-Za-z0-9_.\-]+)==", lock.read_text(), re.M)]


def _tcl_tk_version() -> str:
    try:
        import tkinter

        return tkinter.Tcl().eval("info patchlevel")
    except Exception:  # noqa: BLE001 - only used as a label
        return ""


def write_third_party_licenses(target: Path) -> None:
    out = ["FileLocker bundles the following third-party software.", "=" * 78, ""]
    names = _lock_names(ROOT / "requirements.txt") + ["pyinstaller"]
    for name in names:
        dist = md.distribution(name)
        meta = dist.metadata
        lic = meta.get("License-Expression") or meta.get("License") or ""
        if len(lic) > 120:
            lic = lic.splitlines()[0]
        out += [f"{dist.name} {dist.version}", f"  License: {lic or 'see text below'}",
                f"  Home: {meta.get('Home-page') or ''}".rstrip(), ""]
        files = [f for f in (dist.files or [])
                 if re.search(r"(LICEN[CS]E|COPYING|NOTICE)", f.name, re.I) and f.suffix not in (".py", ".pyc")]
        for f in sorted(files, key=str):
            try:
                text = Path(f.locate()).read_text(encoding="utf-8", errors="replace").strip()
            except OSError:
                continue
            out += [f"----- {f} -----", text, ""]
        if name == "pyinstaller":
            out += ["Note: only PyInstaller's bootloader is included in FileLocker.exe. Its license",
                    "(GPL with a special exception) explicitly allows distributing programs built with it.", ""]
        out += ["=" * 78, ""]
    # Python's own license, and the Tcl/Tk license (Tcl and Tk share one BSD-style text).
    # Prefer the Tcl/Tk license PyInstaller copied into the build - it belongs to the exact
    # Tcl/Tk that ships - and fall back to Python's install folder (layouts differ between
    # the python.org installer and GitHub's hosted Python).
    base = Path(sys.base_prefix)
    internal = DIST / "_internal"
    runtime = (("Python", [base / "LICENSE.txt"]),
               (f"Tcl/Tk {_tcl_tk_version()}".strip(),
                [internal / "_tk_data" / "license.terms",
                 internal / "_tcl_data" / "license.terms",
                 *sorted((base / "tcl").glob("t*/license.terms")),
                 ROOT / "licenses" / "TCL_TK_LICENSE.txt"]))
    for label, candidates in runtime:
        for p in candidates:
            if p.exists():
                origin = next((r for r in (internal, base, ROOT) if p.is_relative_to(r)), p.parent)
                shown = p.relative_to(origin)
                out += [f"{label} (bundled runtime)", f"----- {shown.as_posix()} -----",
                        p.read_text(encoding="utf-8", errors="replace").strip(), "", "=" * 78, ""]
                break
        else:
            sys.exit(f"License text for {label} not found (looked in {internal} and {base}) - not building.")
    target.write_text("\n".join(out), encoding="utf-8")


def run_pyinstaller(version_file: Path) -> None:
    for d in (WORK / "FileLocker", DIST):
        shutil.rmtree(d, ignore_errors=True)
    cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--onedir", "--windowed",
           "--name", "FileLocker", "--version-file", str(version_file),
           "--workpath", str(WORK), "--specpath", str(WORK), "--distpath", str(ROOT / "dist")]
    for mod in EXCLUDE:
        cmd += ["--exclude-module", mod]
    cmd.append(str(ROOT / "main.py"))
    subprocess.run(cmd, cwd=ROOT, check=True)


def run_selftest(report: Path) -> None:
    exe = DIST / "FileLocker.exe"
    report.unlink(missing_ok=True)
    proc = subprocess.run([str(exe), "--selftest", str(report)], cwd=DIST, timeout=600)
    text = report.read_text(encoding="utf-8") if report.exists() else "(no report written)"
    print(text)
    for leftover in DIST.glob("filelocker.log*"):
        leftover.unlink()
    if proc.returncode != 0 or "RESULT: PASS" not in text:
        sys.exit("Self-test of the built exe FAILED - not releasing.")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def make_release_zip() -> Path:
    RELEASE.mkdir(exist_ok=True)
    zpath = RELEASE / f"FileLocker-{version.__version__}-win64.zip"
    zpath.unlink(missing_ok=True)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for f in sorted(DIST.rglob("*")):
            if f.is_file():
                z.write(f, Path("FileLocker") / f.relative_to(DIST))
    return zpath


def main() -> None:
    meta = build_metadata()
    log(f"Building FileLocker {version.__version__}, commit {meta['commit']} ({meta['builder']})")
    write_build_info(meta)
    try:
        version_file = write_version_resource(meta)
        log("Running PyInstaller (onedir, windowed; network modules excluded: " + ", ".join(EXCLUDE) + ")")
        run_pyinstaller(version_file)
    finally:
        (ROOT / "_build_info.py").unlink(missing_ok=True)

    log("Adding documentation and third-party licenses")
    for doc in DOCS:
        if (ROOT / doc).exists():
            shutil.copy2(ROOT / doc, DIST / doc)
    write_third_party_licenses(DIST / "THIRD_PARTY_LICENSES.txt")

    log("Running the built exe's self-test")
    RELEASE.mkdir(exist_ok=True)
    report = RELEASE / f"FileLocker-{version.__version__}-selftest.txt"
    run_selftest(report)

    log("Packaging")
    zpath = make_release_zip()
    exe_hash = sha256(DIST / "FileLocker.exe")
    sums = [f"{sha256(zpath)}  {zpath.name}", f"{exe_hash}  FileLocker/FileLocker.exe"]
    (RELEASE / "SHA256SUMS.txt").write_text("\n".join(sums) + "\n", encoding="utf-8")
    log(f"Done: {zpath}")
    print("\n".join(sums))


if __name__ == "__main__":
    main()
