"""Version and build information.

`_build_info.py` is generated by scripts/build.py at build time (it is not in
git); when running from source it is absent and the commit shows as "source".
"""

__version__ = "1.0.0"
APP_NAME = "FileLocker"


def build_info() -> dict:
    try:
        import _build_info  # type: ignore[import-not-found]

        return {"commit": _build_info.COMMIT, "build_date": _build_info.BUILD_DATE,
                "builder": _build_info.BUILDER}
    except ImportError:
        return {"commit": "source", "build_date": "", "builder": "running from source"}


def version_string() -> str:
    info = build_info()
    commit = info["commit"]
    short = commit[:12] if commit not in ("source", "unknown") else commit
    return f"{APP_NAME} {__version__} ({short})"
